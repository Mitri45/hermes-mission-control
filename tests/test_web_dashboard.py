    def test_operations_stream_websocket_requires_token(self, client):
        """WebSocket operations stream should reject unauthenticated clients."""
        with pytest.raises(WebSocketDisconnect) as exc:
            with client.websocket_connect("/api/operations/stream"):
                pass
        assert exc.value.code == 1008

    def test_operations_stream_websocket_accepts_token(self, client, monkeypatch):
        """WebSocket operations stream accepts auth token via query parameter."""
        monkeypatch.setattr(main_module.settings, "dashboard_auth_mode", "public")
        token = main_module.settings.bearer_token
        with client.websocket_connect(f"/api/operations/stream?token={token}") as websocket:
            websocket.send_text("ping")
            payload = websocket.receive_json()
        assert payload["type"] == "ack"
        assert payload["data"] == "ping"

    def test_operations_stream_websocket_accepts_subprotocol_token(self, client, monkeypatch):
        """WebSocket operations stream accepts auth token via subprotocol."""
        monkeypatch.setattr(main_module.settings, "dashboard_auth_mode", "public")
        encoded = base64.urlsafe_b64encode(main_module.settings.bearer_token.encode("utf-8")).decode("ascii").rstrip("=")
        subprotocols = ["hermes-ops.v1", f"hermes-auth.{encoded}"]
        with client.websocket_connect("/api/operations/stream", subprotocols=subprotocols) as websocket:
            websocket.send_text("ping")
            payload = websocket.receive_json()
            accepted_subprotocol = websocket.accepted_subprotocol
        assert payload["type"] == "ack"
        assert payload["data"] == "ping"
        assert accepted_subprotocol == "hermes-ops.v1"

    def test_operations_stream_websocket_accepts_cloudflare_access_on_loopback(self, client, monkeypatch):
        """Loopback-only Cloudflare Access traffic should be enough for browser websocket auth."""
        monkeypatch.setattr(main_module.settings, "dashboard_auth_mode", "cloudflare")
        monkeypatch.setattr(main_module.settings, "dashboard_shared_secret", None)
        monkeypatch.setenv("MC_HOST", "127.0.0.1")
