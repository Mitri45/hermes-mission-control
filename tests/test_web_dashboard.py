    def test_memory_ingest_offloads_sync_service_from_running_event_loop(self, client, monkeypatch):
        """Ingest should run in a worker thread so sync Hindsight wrappers do not hit nested-loop errors."""

        class FakeService:
            def authenticate_request(self, **kwargs):
                return None

            def ingest(self, events):
                try:
                    loop = asyncio.get_event_loop()
                except RuntimeError:
                    loop = asyncio.new_event_loop()
                    asyncio.set_event_loop(loop)
                assert threading.current_thread() is not threading.main_thread()
                loop.run_until_complete(asyncio.sleep(0))
                return MemoryIngestResponse(
                    accepted=len(events),
                    duplicates=0,
                    dead_lettered=0,
                    transient_failures=0,
                    checkpoints=[],
                    results=[],
                )

        monkeypatch.setattr("app.api.memory_ingest.get_memory_ingest_service", lambda: FakeService())
        response = client.post(
            "/api/memory/ingest",
            headers={
                "X-Hermes-Timestamp": "1712870400",
                "X-Hermes-Nonce": "nonce-test-12345",
                "X-Hermes-Signature": "sha256=dummy",
            },
            json={
                "events": [
                    {
                        "event_id": "evt-1",
                        "source_peer": "pi",
                        "seq": 1,
                        "ts": "2026-04-12T00:00:00Z",
                        "type": "user_message",
                        "payload": {"content": "test"},
                        "payload_hash": "abc",
                    }
                ]
            },
        )
        assert response.status_code == 200
        assert response.json()["accepted"] == 1

